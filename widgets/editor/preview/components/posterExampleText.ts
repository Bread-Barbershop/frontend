interface PosterLayer {
  text?: string;
  visible?: boolean;
  opacity?: number;
  isOnScreen?: () => boolean;
  getObjects?: () => PosterLayer[];
}

export function getPosterExampleText(layers: PosterLayer[]): string[] {
  const examples = new Set<string>();
  function visit(layer: PosterLayer) {
    if (layer.visible === false || layer.opacity === 0) return;
    const text = layer.text?.replace(/\s+/g, ' ').trim();
    if (text && exampleDetails.has(text.toLowerCase())) examples.add(text);
    layer.getObjects?.().forEach(visit);
  }
  layers.filter(layer => layer.isOnScreen?.() !== false).forEach(visit);
  return [...examples];
}
